/**
 * Devuelve el SVG de un icono. Decorativo por defecto (`aria-hidden`): el
 * texto que lo acompaña ya dice lo que hace. Si el icono va solo, pásale un
 * `label` y se anuncia como imagen con nombre.
 */
function icon(name, label) {
    const paths = ICONS[name];
    if (!paths) {
        console.warn(`Icono desconocido: ${name}`);
        return '';
    }

    const a11y = label
        ? `role="img" aria-label="${label}"`
        : 'aria-hidden="true" focusable="false"';

    return `<svg class="icon icon-${name}" ${a11y} width="1em" height="1em" `
        + `viewBox="0 0 16 16" fill="currentColor">`
        + paths.split('|').map((d) => `<path d="${d}"/>`).join('')
        + `</svg>`;
}

/** Sustituye los `<i data-icon="nombre">` del HTML estático. */
function renderIcons(root = document) {
    root.querySelectorAll('[data-icon]').forEach((el) => {
        el.outerHTML = icon(el.dataset.icon, el.dataset.iconLabel);
    });
}

window.Icons = { icon, renderIcons, ICONS };

document.addEventListener('DOMContentLoaded', () => renderIcons());
